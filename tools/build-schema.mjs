// Regenerates supabase/schema.sql (the one-file setup for a new project) from
// the migrations, in order. `node tools/build-schema.mjs --check` fails when stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `-- ===== ${f} =====\n` + readFileSync(join(dir, f), 'utf8').trimEnd() + '\n').join('\n');
const out = '-- Generated by `npm run schema` from supabase/migrations. Do not edit by hand.\n' +
  '-- New project: paste this whole file into the Supabase SQL Editor and run it once.\n' +
  '-- Existing project: run only the migrations you have not applied yet, in order.\n\n' + body;

if (process.argv.includes('--check')) {
  if (readFileSync('supabase/schema.sql', 'utf8') !== out) {
    console.error('supabase/schema.sql is out of date. Run `npm run schema`.');
    process.exit(1);
  }
} else {
  writeFileSync('supabase/schema.sql', out);
  console.log('Wrote supabase/schema.sql from', files.length, 'migrations');
}
